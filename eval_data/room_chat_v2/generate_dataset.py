def generate() -> None:
    rng = random.Random(SEED)
    rows: list[dict[str, object]] = []
    evidence_seq: dict[tuple[str, int], int] = {}
    scenario_by_stage = [
        (scenario_index, stage)
        for stage in (0, 1)
        for scenario_index in range(len(SCENARIOS))
    ]
    filler_index = 0

    def add_message(sender_index: int, content: str) -> None:
        seq = len(rows) + 1
        sender_id, sender_name = PEOPLE[sender_index]
        rows.append({
            "message_id": f"v2-msg-{seq:06d}", "room_id": ROOM_ID,
            "conversation_id": CONVERSATION_ID, "sender_id": sender_id,
            "sender_name": sender_name, "seq": seq, "type": 0,
            "content": content, "status": 0,
            "send_time": int(datetime(2025, 3, 1, tzinfo=timezone.utc).timestamp()) + seq * 90,
        })

    def add_filler() -> None:
        nonlocal filler_index
        template = FILLER_TEMPLATES[filler_index % len(FILLER_TEMPLATES)]
        values = {key: rng.choice(options) for key, options in FILLER_VALUES.items()}
        content = template.format(**values)
        if filler_index % 31 == 4:
            content += rng.choice([" 哈哈", "😂", "我先记一下", "确实，回头再说"])
        elif filler_index % 47 == 9:
            content = rng.choice(["嗯嗯", "收到，我晚点看", "这个可以", "我也遇到过", "等我确认一下"])
        add_message(rng.randrange(len(PEOPLE)), content)
        filler_index += 1

    stage_positions = [
        round((position + 0.5) * MESSAGE_COUNT / len(scenario_by_stage))
        for position in range(len(scenario_by_stage))
    ]
    event_index = 0
    while len(rows) < MESSAGE_COUNT:
        if event_index < len(scenario_by_stage) and len(rows) + 1 >= stage_positions[event_index]:
            scenario_index, stage = scenario_by_stage[event_index]
            scenario = SCENARIOS[scenario_index]
            start = 0 if stage == 0 else 4
            for local_index, (sender_index, content) in enumerate(scenario["messages"][start:start + 4]):
                evidence_seq[(scenario["label"], start + local_index)] = len(rows) + 1
                add_message(sender_index, content)
            event_index += 1
        else:
            add_filler()

    queries: list[dict[str, object]] = []
    for scenario in SCENARIOS:
        for question, answer, indices in scenario["queries"]:
            queries.append({
                "qid": f"v2-q-{len(queries) + 1:03d}",
                "room_id": ROOM_ID,
                "question": question,
                "answerable": True,
                "answer": answer,
                "gold_seqs": [evidence_seq[(scenario["label"], index)] for index in indices],
                "category": scenario["label"],
                "source": "manual_scenario",
            })
    for question in UNANSWERABLE:
        queries.append({
            "qid": f"v2-q-{len(queries) + 1:03d}", "room_id": ROOM_ID,
            "question": question, "answerable": False, "answer": None,
            "gold_seqs": [], "category": "unanswerable", "source": "manual_unanswerable",
        })

    assert len(rows) == MESSAGE_COUNT
    assert len(queries) == len(SCENARIOS) * 4 + len(UNANSWERABLE)
    assert sum(bool(row["answerable"]) for row in queries) == len(SCENARIOS) * 4
    assert all(1 <= seq <= MESSAGE_COUNT for row in queries for seq in row["gold_seqs"])
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for filename, records in (("corpus.jsonl", rows), ("queries.jsonl", queries)):
        with (OUT_DIR / filename).open("w", encoding="utf-8") as file:
            for record in records:
                file.write(json.dumps(record, ensure_ascii=False) + "\n")
    print(f"messages={len(rows)} answerable={sum(bool(row['answerable']) for row in queries)} unanswerable={sum(not bool(row['answerable']) for row in queries)}")


if __name__ == "__main__":
    generate()
